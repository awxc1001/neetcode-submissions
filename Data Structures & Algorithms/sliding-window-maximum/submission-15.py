        fast = 0          # 右指针：代表当前正要吃进窗口的元素位置
        slow = 0          # 左指针：代表当前窗口的逻辑左边界
        mono_q = deque()  # 单调队列：只存索引！队头 nums[mono_q[0]] 永远是当前窗口最大值
        res = []

        # 开始滑动窗口模板
        while fast < len(nums):
            # ---------------------------------------------------------------
            # 1. 扩大窗口：无脑把当前 fast 指向的新元素吃进队列
            # ---------------------------------------------------------------
            # 核心细节：新来一个数，要把队列尾部（右侧）所有比它小的数都干掉！
            # 注意：是用 mono_q.pop() 从尾部弹，绝对不能用 popleft() 误伤了左边的队头大数。
            while mono_q and nums[mono_q[-1]] <= nums[fast]:
                mono_q.pop()
            
            # 把新元素的索引安全压入队列
            mono_q.append(fast)
            
            # 【严格遵循模板节奏】：让右指针先往前走一步
            # 此时 fast 变成了下一个位置，当前窗口在指针上的虚拟长度就是 (fast - slow)
            fast += 1

            # ---------------------------------------------------------------
            # 2. 检查并擦屁股：如果窗口超长了（长度达到 k + 1），立刻触发裁剪
            # ---------------------------------------------------------------
            # 核心卡点 1：为什么是 while fast - slow > k？
            # - 当第一次凑齐 k 个数时，fast - slow 刚好等于 k，这个条件不成立，直接跳过裁剪，去第 3 步收答案。
            # - 之后每走一步，长度变成 k + 1，就会触发这个 while 进来裁剪，把它缩回 k。
            while fast - slow > k:
                
                # 【🚨 之前搞不懂的致命卡点 2】：这里必须写 == slow，绝对不能写 < slow ！
                #
                # 为什么？因为此时代码是一行行执行的，下面的 slow += 1 还没有发生呢！
                # 这一瞬间，slow 对应的正是当下【马上就要被无情扔掉】的那个旧左边界索引。
                # 
                # 假设面临淘汰的旧左边界索引是 0：
                # - 如果写 == slow：(0 == 0) 成立，队列里过期的死鬼大数被完美拦截并 popleft() 弹出。
                # - 如果写 < slow：(0 < 0) 变成不成立！代码会直接跳过弹出，导致过期的最大值留在队列里，污染后面的答案！
                #
                # 事实上，因为每次循环窗口最多只超长 1 个数，面临淘汰的永远只有当前这一个 slow，
                # 比 slow 还要小的旧索引在以前的轮次里早就死光了。所以写 == slow 才是最纯粹、最精准的拦截。

                #if biggest is the going to be expired index
                if mono_q[0] == slow:
                    mono_q.popleft()
                
                # 【🚀 之前搞不懂的致命卡点 3：关于 O(n) 的底层秘密】
                # 过去我们写 window.pop(0) 会导致后面所有元素在内存里挪位，硬生生把时间复杂度拉高成了 O(nk)。
                # 现在我们不需要真实的物理数组了，让指针 slow += 1 往右挪一格。
                # 计算机只是改了个数字，内存里的元素动都不用动，这是纯正的 O(1) 操作！
                # 加上每个元素一生只进队一次、出队一次，总时间复杂度被完美优化到了最优的 O(n)！
                slow += 1

            # ---------------------------------------------------------------
            # 3. 收集答案：经过上面的收缩，此时窗口必然处于百分之百合法状态（长度完美等于 k）
            # ---------------------------------------------------------------
            if fast - slow == k:
                res.append(nums[mono_q[0]])

        return res

